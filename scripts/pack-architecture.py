"""Repack architecture assets without changing a single RGBE pixel or GLB byte.
Build-time dependency: numpy. No server/runtime dependency.
"""
from pathlib import Path
import gzip,struct,json
import numpy as np
root=Path(__file__).resolve().parents[1]/'site/assets/architecture'
def decode(path):
 data=path.read_bytes();pos=data.index(b'\n-Y ')+1;end=data.index(b'\n',pos);_,hs,_,ws=data[pos:end].split();w,h=int(ws),int(hs);pos=end+1;out=np.empty((h,4,w),dtype=np.uint8)
 for y in range(h):
  if data[pos:pos+4]!=bytes([2,2,w>>8,w&255]):raise ValueError('Unsupported HDR scanline')
  pos+=4
  for c in range(4):
   x=0
   while x<w:
    n=data[pos];pos+=1
    if n>128:n-=128;out[y,c,x:x+n]=data[pos];pos+=1
    else:out[y,c,x:x+n]=np.frombuffer(data,dtype=np.uint8,count=n,offset=pos);pos+=n
    x+=n
   if x!=w:raise ValueError('Invalid HDR run')
 if pos!=len(data):raise ValueError('Unexpected HDR payload')
 return out
manifest={}
for name in ['building.glb','v16-display-lut.bin']:
 raw=(root/name).read_bytes();packed=gzip.compress(raw,compresslevel=9,mtime=0);(root/(name+'.gz')).write_bytes(packed);manifest[name]={'file':name+'.gz','encoding':'gzip','bytes':len(packed),'originalBytes':len(raw)}
for name in ['v16-stone-diffuse','v16-concrete-diffuse','v16-local-radiance']:
 original=root/(name+'.hdr');pixels=decode(original);h,_,w=pixels.shape;delta=np.concatenate([pixels[:1],np.diff(pixels,axis=0)],axis=0);payload=struct.pack('<4sIII',b'LRGB',1,w,h)+delta.tobytes();packed=gzip.compress(payload,compresslevel=9,mtime=0);file=name+'.rgbe.gz';(root/file).write_bytes(packed);manifest[original.name]={'file':file,'encoding':'rgbe-delta','bytes':len(packed),'originalBytes':original.stat().st_size}
(root.parents[1]/'architecture-manifest.js').write_text('// Generated by scripts/pack-architecture.py. Lossless transport only.\nexport const architectureAssets='+json.dumps(manifest,separators=(',',':'))+';\n',encoding='utf-8')
print(json.dumps({'before':sum(v['originalBytes']for v in manifest.values()),'after':sum(v['bytes']for v in manifest.values())}))
